const assert=require('node:assert/strict');
const geo=require('../dist/geo.js');
const now=Date.now();
const pos=(accuracy,age=0,latitude=-6.23,longitude=106.8)=>({timestamp:now-age,coords:{latitude,longitude,accuracy}});
assert.equal(geo.valid(pos(20),now),true);
assert.equal(geo.valid(pos(20,61000),now),false);
assert.equal(geo.valid(pos(20,0,91),now),false);
assert.equal(geo.valid(pos(NaN),now),false);
assert.equal(geo.valid(pos(0),now),false);
assert.equal(geo.distance(pos(10).coords,pos(10).coords),0);
let chosen=geo.choose([pos(8,1000)],pos(35),now);
assert.equal(chosen.position.coords.accuracy,8);
chosen=geo.choose([pos(8,16000)],pos(35),now);
assert.equal(chosen.position.coords.accuracy,35);
chosen=geo.choose([pos(8,1000)],pos(12,0,-6.25),now);
assert.equal(chosen.samples.length,1);
assert.equal(chosen.position.coords.latitude,-6.25);
assert.equal(geo.choose([pos(10)],pos(5,1000),now).position,null);
assert.equal(geo.choose([],pos(5,61000),now).position,null);
// Fixtures test parsing only. These are not live geocoding results.
const a=geo.address({address:{road:'Jalan Contoh',house_number:'7',neighbourhood:'RW 01',village:'Kelurahan Contoh',city_district:'Kecamatan Contoh',municipality:'Kota Administrasi Contoh',state:'Provinsi Contoh',postcode:'12345',country:'Indonesia'}});
for(const text of ['Jalan Contoh No. 7','RW 01','Kelurahan Contoh','Kecamatan Contoh','Kota Administrasi Contoh','12345'])assert.ok(a.text.includes(text));
assert.equal(a.missing.length,0);
assert.equal(geo.address({address:{road:'Jalan Contoh',suburb:'Selong'}}).text,'Jalan Contoh, Selong');
assert.ok(!geo.address({address:{road:'Jalan Contoh'}}).text.includes('Jakarta'));
assert.equal(geo.address({address:{city:'Contoh',municipality:'Contoh'}}).text,'Contoh');
assert.equal(geo.address({display_name:'Alamat dari penyedia',address:{}}).text,'Alamat dari penyedia');
assert.equal(geo.address({}).text,'');
assert.ok(geo.address({}).missing.includes('kode pos'));
console.log('PASS: valid/stale/invalid GPS, best recent sample, movement reset, out-of-order sample, full address, no invented fields, deduplication and empty data');
